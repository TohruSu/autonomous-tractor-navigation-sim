#!/usr/bin/env python3
"""Render a deterministic SVG from the standalone simulator's synthetic CSV output.

Usage: python3 scripts/plot_trajectories.py --samples artifacts/demo/samples.csv \
           --summary artifacts/demo/summary.csv --output docs/images/tracking-comparison.svg
No third-party Python packages or historical data are required.
"""

import argparse
import csv
import math
from pathlib import Path

SCENARIO = "left-turn-offset"
CONTROLLERS = (
    ("Stanley(gain=1,speedSoftening=0.5)", "Stanley", "#1673b1"),
    ("PurePursuit(lookahead=1,speedGain=0.3)", "Pure Pursuit", "#dc742d"),
)


def load_data(samples_path: Path, summary_path: Path):
    with samples_path.open(newline="", encoding="utf-8") as file:
        samples = list(csv.DictReader(file))
    with summary_path.open(newline="", encoding="utf-8") as file:
        summaries = list(csv.DictReader(file))
    traces = []
    for key, display_name, color in CONTROLLERS:
        group = [row for row in samples if row["scenario"] == SCENARIO and row["controller"] == key]
        summary = [row for row in summaries if row["scenario"] == SCENARIO and row["controller"] == key]
        if len(group) < 2 or len(summary) != 1 or summary[0]["status"] != "Completed":
            raise ValueError(f"Missing complete simulator output for {SCENARIO} / {key}")
        points = [(float(row["x_m"]), float(row["y_m"])) for row in group]
        error = float(summary[0]["rms_cross_track_error_m"])
        if not math.isfinite(error) or not all(math.isfinite(x) and math.isfinite(y) for x, y in points):
            raise ValueError(f"Nonfinite trajectory or RMS error for {key}")
        if points[0] != (0.0, 0.5):
            raise ValueError(f"Unexpected initial condition in {SCENARIO}: {points[0]}")
        traces.append((display_name, color, points, error))
    return traces


def render(traces):
    # Same synthetic quarter circle used in ScenarioCatalog/RouteFactory: R = 6m.
    # The simulator tracks a 0.05m sampled polyline approximation of this arc.
    route = [(6 * math.sin(math.pi * i / 360),
              6 * (1 - math.cos(math.pi * i / 360))) for i in range(181)]
    xmin, xmax = -0.8, 7.6
    ymin, ymax = -0.8, 7.6
    left, top, plot_size = 100, 100, 510
    scale = plot_size / (xmax - xmin)

    def px(x):
        return left + (x - xmin) * scale

    def py(y):
        return top + (ymax - y) * scale

    def path(points):
        # Reduce SVG size without altering or recomputing the simulator's data.
        skip = max(1, (len(points) - 1) // 150)
        selected = points[::skip]
        if selected[-1] != points[-1]:
            selected.append(points[-1])
        return " ".join(("M" if i == 0 else "L") + f"{px(x):.2f},{py(y):.2f}"
                        for i, (x, y) in enumerate(selected))

    svg = [
        '<svg xmlns="http://www.w3.org/2000/svg" width="1000" height="665" viewBox="0 0 1000 665" role="img" aria-labelledby="heading details">',
        '<title id="heading">Synthetic tractor navigation: Stanley versus Pure Pursuit</title>',
        '<desc id="details">Reference radius-six-metre left turn and two trajectories generated by the C# simulator from the same 0.5 metre initial offset.</desc>',
        '<rect width="1000" height="665" rx="18" fill="#ffffff"/>',
        '<text x="74" y="38" font-family="Arial,Helvetica,sans-serif" font-size="25" font-weight="700" fill="#18283b">Path tracking on a synthetic left turn</text>',
        '<text x="75" y="65" font-family="Arial,Helvetica,sans-serif" font-size="14" fill="#5a6777">Same route, speed and steering limits  ·  deterministic bicycle simulation</text>',
        f'<rect x="{left}" y="{top}" width="{plot_size}" height="{plot_size}" fill="#fafbfd" stroke="#cfd8e3"/>',
    ]
    for tick in (0, 2, 4, 6):
        x, y = px(tick), py(tick)
        svg += [
            f'<line x1="{x:.2f}" y1="{top}" x2="{x:.2f}" y2="{top+plot_size}" stroke="#e1e8ef" stroke-width="1"/>',
            f'<line x1="{left}" y1="{y:.2f}" x2="{left+plot_size}" y2="{y:.2f}" stroke="#e1e8ef" stroke-width="1"/>',
            f'<text x="{x:.2f}" y="{top+plot_size+23}" text-anchor="middle" font-family="Arial,Helvetica,sans-serif" font-size="13" fill="#526276">{tick}</text>',
            f'<text x="{left-16}" y="{y+4:.2f}" text-anchor="end" font-family="Arial,Helvetica,sans-serif" font-size="13" fill="#526276">{tick}</text>',
        ]
    svg.extend([
        f'<text x="{left+plot_size/2:.2f}" y="{top+plot_size+52}" text-anchor="middle" font-family="Arial,Helvetica,sans-serif" font-size="15" fill="#35465c">X (metres)</text>',
        f'<text transform="translate(35 {top+plot_size/2:.2f}) rotate(-90)" text-anchor="middle" font-family="Arial,Helvetica,sans-serif" font-size="15" fill="#35465c">Y (metres)</text>',
        f'<path d="{path(route)}" fill="none" stroke="#6f7f91" stroke-dasharray="8 7" stroke-width="3" stroke-linecap="round" stroke-linejoin="round"/>',
    ])
    for name, color, points, rms in traces:
        svg.append(f'<path d="{path(points)}" fill="none" stroke="{color}" stroke-width="3.4" stroke-linecap="round" stroke-linejoin="round"/>')
        svg.append(f'<circle cx="{px(points[-1][0]):.2f}" cy="{py(points[-1][1]):.2f}" r="5" fill="{color}" stroke="white" stroke-width="1.5"/>')
    svg.extend([
        f'<circle cx="{px(0):.2f}" cy="{py(0.5):.2f}" r="5.5" fill="#1d2939" stroke="white" stroke-width="1.5"/>',
        '<text x="673" y="126" font-family="Arial,Helvetica,sans-serif" font-size="20" font-weight="700" fill="#18283b">Route comparison</text>',
        '<line x1="673" y1="154" x2="710" y2="154" stroke="#6f7f91" stroke-width="3" stroke-dasharray="8 6"/>',
        '<text x="725" y="159" font-family="Arial,Helvetica,sans-serif" font-size="15" fill="#2e4055">Reference path</text>',
    ])
    for i, (name, color, points, rms) in enumerate(traces):
        y = 195 + 85 * i
        svg += [
            f'<line x1="673" y1="{y}" x2="710" y2="{y}" stroke="{color}" stroke-width="4"/>',
            f'<text x="725" y="{y+5}" font-family="Arial,Helvetica,sans-serif" font-size="17" font-weight="600" fill="#243449">{name}</text>',
            f'<text x="725" y="{y+31}" font-family="Arial,Helvetica,sans-serif" font-size="14" fill="#55667a">RMS CTE: {rms:.3f} m</text>',
        ]
    svg.extend([
        '<text x="674" y="398" font-family="Arial,Helvetica,sans-serif" font-size="16" font-weight="700" fill="#243449">Synthetic conditions</text>',
        '<text x="674" y="428" font-family="Arial,Helvetica,sans-serif" font-size="14" fill="#526276">Turn radius: 6 m</text>',
        '<text x="674" y="452" font-family="Arial,Helvetica,sans-serif" font-size="14" fill="#526276">Initial lateral offset: +0.5 m</text>',
        '<text x="674" y="476" font-family="Arial,Helvetica,sans-serif" font-size="14" fill="#526276">Speed: 1 m/s</text>',
        '<text x="674" y="500" font-family="Arial,Helvetica,sans-serif" font-size="14" fill="#526276">Integration step: 0.02 s</text>',
        '<text x="674" y="540" font-family="Arial,Helvetica,sans-serif" font-size="12" fill="#68788c">CTE = cross-track error</text>',
        '<text x="74" y="650" font-family="Arial,Helvetica,sans-serif" font-size="12" fill="#68788c">Illustration generated from the simulator’s synthetic samples.csv and summary.csv. Not field-test data.</text>',
        '</svg>',
    ])
    return "".join(svg) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--samples", type=Path, required=True)
    parser.add_argument("--summary", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    data = render(load_data(args.samples, args.summary))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(data, encoding="utf-8", newline="\n")
    print(f"Created synthetic trajectory chart: {args.output}")


if __name__ == "__main__":
    main()
